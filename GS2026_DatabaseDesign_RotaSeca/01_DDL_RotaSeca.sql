CREATE TABLE RS_BAIRRO (
    ID_BAIRRO     NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    NM_BAIRRO     VARCHAR2(80)  NOT NULL,
    NM_REGIAO     VARCHAR2(30)  NOT NULL,
    NM_CIDADE     VARCHAR2(60)  NOT NULL,
    NR_POPULACAO  NUMBER(9)
);

CREATE TABLE RS_PONTO_RISCO (
    ID_PONTO_RISCO    NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
    ID_BAIRRO         NUMBER(10)     NOT NULL,
    DS_LOCAL          VARCHAR2(150)  NOT NULL,
    NR_LATITUDE       NUMBER(9,6)    NOT NULL,
    NR_LONGITUDE      NUMBER(9,6)    NOT NULL,
    DS_NIVEL_RISCO    VARCHAR2(12)   NOT NULL,
    NR_LAMINA_MAX_CM  NUMBER(5,1)
);

CREATE TABLE RS_PONTO_APOIO (
    ID_PONTO_APOIO  NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
    ID_BAIRRO       NUMBER(10)     NOT NULL,
    NM_PONTO        VARCHAR2(100)  NOT NULL,
    DS_TIPO         VARCHAR2(10)   NOT NULL,
    DS_ENDERECO     VARCHAR2(150)  NOT NULL,
    NR_LATITUDE     NUMBER(9,6)    NOT NULL,
    NR_LONGITUDE    NUMBER(9,6)    NOT NULL,
    NR_CAPACIDADE   NUMBER(5)      NOT NULL,
    ST_ATIVO        CHAR(1)        DEFAULT 'S' NOT NULL
);

CREATE TABLE RS_LEITURA_CHUVA (
    ID_LEITURA          NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    ID_BAIRRO           NUMBER(10)    NOT NULL,
    DT_LEITURA          TIMESTAMP     NOT NULL,
    VL_PRECIPITACAO_MM  NUMBER(6,2)   NOT NULL,
    VL_UMIDADE          NUMBER(5,2),
    DS_FONTE            VARCHAR2(60)  NOT NULL
);

CREATE TABLE RS_ALERTA (
    ID_ALERTA    NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
    ID_BAIRRO    NUMBER(10)     NOT NULL,
    ID_LEITURA   NUMBER(10),
    DS_NIVEL     VARCHAR2(12)   NOT NULL,
    DS_MENSAGEM  VARCHAR2(400)  NOT NULL,
    DT_EMISSAO   TIMESTAMP      NOT NULL,
    DT_VALIDADE  TIMESTAMP      NOT NULL
);

CREATE TABLE RS_MORADOR (
    ID_MORADOR              NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
    ID_BAIRRO               NUMBER(10)     NOT NULL,
    NM_MORADOR              VARCHAR2(100)  NOT NULL,
    NR_TELEFONE             VARCHAR2(20)   NOT NULL,
    DT_NASCIMENTO           DATE           NOT NULL,
    ST_MOBILIDADE_REDUZIDA  CHAR(1)        DEFAULT 'N' NOT NULL,
    ST_RECEBE_ALERTA        CHAR(1)        DEFAULT 'S' NOT NULL
);

CREATE TABLE RS_OCORRENCIA (
    ID_OCORRENCIA   NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
    ID_PONTO_RISCO  NUMBER(10)     NOT NULL,
    ID_MORADOR      NUMBER(10),
    DT_OCORRENCIA   TIMESTAMP      NOT NULL,
    NR_LAMINA_CM    NUMBER(5,1)    NOT NULL,
    DS_OBSERVACAO   VARCHAR2(300),
    DS_STATUS       VARCHAR2(15)   DEFAULT 'ABERTA' NOT NULL
);

ALTER TABLE RS_BAIRRO        ADD CONSTRAINT PK_RS_BAIRRO        PRIMARY KEY (ID_BAIRRO);
ALTER TABLE RS_PONTO_RISCO   ADD CONSTRAINT PK_RS_PONTO_RISCO   PRIMARY KEY (ID_PONTO_RISCO);
ALTER TABLE RS_PONTO_APOIO   ADD CONSTRAINT PK_RS_PONTO_APOIO   PRIMARY KEY (ID_PONTO_APOIO);
ALTER TABLE RS_LEITURA_CHUVA ADD CONSTRAINT PK_RS_LEITURA_CHUVA PRIMARY KEY (ID_LEITURA);
ALTER TABLE RS_ALERTA        ADD CONSTRAINT PK_RS_ALERTA        PRIMARY KEY (ID_ALERTA);
ALTER TABLE RS_MORADOR       ADD CONSTRAINT PK_RS_MORADOR       PRIMARY KEY (ID_MORADOR);
ALTER TABLE RS_OCORRENCIA    ADD CONSTRAINT PK_RS_OCORRENCIA    PRIMARY KEY (ID_OCORRENCIA);

ALTER TABLE RS_PONTO_RISCO ADD CONSTRAINT FK_RS_PR_BAIRRO
    FOREIGN KEY (ID_BAIRRO) REFERENCES RS_BAIRRO (ID_BAIRRO);

ALTER TABLE RS_PONTO_APOIO ADD CONSTRAINT FK_RS_PA_BAIRRO
    FOREIGN KEY (ID_BAIRRO) REFERENCES RS_BAIRRO (ID_BAIRRO);

ALTER TABLE RS_LEITURA_CHUVA ADD CONSTRAINT FK_RS_LC_BAIRRO
    FOREIGN KEY (ID_BAIRRO) REFERENCES RS_BAIRRO (ID_BAIRRO);

ALTER TABLE RS_ALERTA ADD CONSTRAINT FK_RS_AL_BAIRRO
    FOREIGN KEY (ID_BAIRRO) REFERENCES RS_BAIRRO (ID_BAIRRO);

ALTER TABLE RS_ALERTA ADD CONSTRAINT FK_RS_AL_LEITURA
    FOREIGN KEY (ID_LEITURA) REFERENCES RS_LEITURA_CHUVA (ID_LEITURA);

ALTER TABLE RS_MORADOR ADD CONSTRAINT FK_RS_MO_BAIRRO
    FOREIGN KEY (ID_BAIRRO) REFERENCES RS_BAIRRO (ID_BAIRRO);

ALTER TABLE RS_OCORRENCIA ADD CONSTRAINT FK_RS_OC_PONTO_RISCO
    FOREIGN KEY (ID_PONTO_RISCO) REFERENCES RS_PONTO_RISCO (ID_PONTO_RISCO);

ALTER TABLE RS_OCORRENCIA ADD CONSTRAINT FK_RS_OC_MORADOR
    FOREIGN KEY (ID_MORADOR) REFERENCES RS_MORADOR (ID_MORADOR);

ALTER TABLE RS_BAIRRO  ADD CONSTRAINT UK_RS_BAIRRO_NOME UNIQUE (NM_BAIRRO, NM_CIDADE);
ALTER TABLE RS_MORADOR ADD CONSTRAINT UK_RS_MORADOR_TEL UNIQUE (NR_TELEFONE);

ALTER TABLE RS_BAIRRO ADD CONSTRAINT CK_RS_BAIRRO_POP
    CHECK (NR_POPULACAO >= 0);

ALTER TABLE RS_PONTO_RISCO ADD CONSTRAINT CK_RS_PR_NIVEL
    CHECK (DS_NIVEL_RISCO IN ('BAIXO', 'MODERADO', 'ALTO', 'MUITO_ALTO'));
ALTER TABLE RS_PONTO_RISCO ADD CONSTRAINT CK_RS_PR_LAMINA
    CHECK (NR_LAMINA_MAX_CM >= 0);

ALTER TABLE RS_PONTO_APOIO ADD CONSTRAINT CK_RS_PA_TIPO
    CHECK (DS_TIPO IN ('ABRIGO', 'ESCOLA', 'UBS', 'OUTRO'));
ALTER TABLE RS_PONTO_APOIO ADD CONSTRAINT CK_RS_PA_CAPACIDADE
    CHECK (NR_CAPACIDADE > 0);
ALTER TABLE RS_PONTO_APOIO ADD CONSTRAINT CK_RS_PA_ATIVO
    CHECK (ST_ATIVO IN ('S', 'N'));

ALTER TABLE RS_LEITURA_CHUVA ADD CONSTRAINT CK_RS_LC_PRECIP
    CHECK (VL_PRECIPITACAO_MM >= 0);
ALTER TABLE RS_LEITURA_CHUVA ADD CONSTRAINT CK_RS_LC_UMIDADE
    CHECK (VL_UMIDADE BETWEEN 0 AND 100);

ALTER TABLE RS_ALERTA ADD CONSTRAINT CK_RS_AL_NIVEL
    CHECK (DS_NIVEL IN ('BAIXO', 'MODERADO', 'ALTO', 'MUITO_ALTO'));
ALTER TABLE RS_ALERTA ADD CONSTRAINT CK_RS_AL_VALIDADE
    CHECK (DT_VALIDADE > DT_EMISSAO);

ALTER TABLE RS_MORADOR ADD CONSTRAINT CK_RS_MO_MOBILIDADE
    CHECK (ST_MOBILIDADE_REDUZIDA IN ('S', 'N'));
ALTER TABLE RS_MORADOR ADD CONSTRAINT CK_RS_MO_ALERTA
    CHECK (ST_RECEBE_ALERTA IN ('S', 'N'));

ALTER TABLE RS_OCORRENCIA ADD CONSTRAINT CK_RS_OC_LAMINA
    CHECK (NR_LAMINA_CM >= 0);
ALTER TABLE RS_OCORRENCIA ADD CONSTRAINT CK_RS_OC_STATUS
    CHECK (DS_STATUS IN ('ABERTA', 'EM_ATENDIMENTO', 'ENCERRADA'));

COMMENT ON TABLE RS_BAIRRO        IS 'Bairros atendidos pela Rota Seca';
COMMENT ON TABLE RS_PONTO_RISCO   IS 'Pontos do bairro que alagam (trechos a evitar)';
COMMENT ON TABLE RS_PONTO_APOIO   IS 'Locais seguros: abrigo, escola, UBS ou outro';
COMMENT ON TABLE RS_LEITURA_CHUVA IS 'Leituras de chuva por bairro, em mm/h';
COMMENT ON TABLE RS_ALERTA        IS 'Alertas emitidos para um bairro, automáticos (a partir de uma leitura) ou manuais';
COMMENT ON TABLE RS_MORADOR       IS 'Moradores cadastrados no aplicativo (dados simulados)';
COMMENT ON TABLE RS_OCORRENCIA    IS 'Alagamentos reportados em pontos de risco';

COMMENT ON COLUMN RS_PONTO_RISCO.DS_NIVEL_RISCO     IS 'BAIXO, MODERADO, ALTO ou MUITO_ALTO';
COMMENT ON COLUMN RS_PONTO_RISCO.NR_LAMINA_MAX_CM   IS 'Maior lâmina d''água já registrada no ponto, em cm';
COMMENT ON COLUMN RS_LEITURA_CHUVA.VL_PRECIPITACAO_MM IS 'Chuva em mm/h; escala CGE: <10 baixo, >=10 moderado, >=25 alto, >=50 muito alto';
COMMENT ON COLUMN RS_ALERTA.ID_LEITURA              IS 'Leitura que gerou o alerta; nulo em alerta manual da Defesa Civil';
COMMENT ON COLUMN RS_OCORRENCIA.ID_MORADOR          IS 'Morador que reportou; nulo em registro anônimo';
COMMENT ON COLUMN RS_OCORRENCIA.DS_STATUS           IS 'ABERTA -> EM_ATENDIMENTO -> ENCERRADA';
